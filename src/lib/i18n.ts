export const LANGS = ["en", "ka-ge"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "en";

export function isLang(v: string): v is Lang {
  return (LANGS as readonly string[]).includes(v);
}

/** Public URL for a path in a language: English has no prefix, Georgian lives under /ka-ge (as on the original site) */
export function localePath(lang: Lang, path: string) {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (lang === "en") return clean;
  return clean === "/" ? "/ka-ge" : `/ka-ge${clean}`;
}

/** Strip the language prefix from a pathname (usePathname can return the internal /en/... route) */
export function stripLang(pathname: string) {
  for (const prefix of ["/ka-ge", "/en"]) {
    if (pathname === prefix) return "/";
    if (pathname.startsWith(`${prefix}/`)) return pathname.slice(prefix.length);
  }
  return pathname;
}

/** Pick the Georgian value when present, falling back to English */
export function pick(lang: Lang, en: string, ka: string | null | undefined) {
  return lang === "ka-ge" && ka ? ka : en;
}

